function step(key, title, summary, input, action, output, source, settings = []) {
  return {
    key, title, summary,
    inputs: [input], actions: [action], outputs: [output],
    parameters: settings.map(([name, value]) => ({name, value})), source,
  };
}

function fractionSteps(label, column, status) {
  return [
    step('definition', 'Resolve the gene set', 'Choose how to define the fraction.',
      'The capture feature map and the configured list of '+label+' gene IDs.',
      'In gene_ids mode, require a nonempty, unique list with a match for every ID in the original feature map. Map the IDs to the assay row names. The default unavailable mode records a missing measurement.',
      'Validated RNA assay rows or an unavailable-definition status.', loader,
      [['mode','Preset: unavailable. Set gene_ids mode only with a verified reference-specific list.'],['feature_id_column','original_feature_id']]),
    step('fraction', 'Calculate the fraction', 'Express the selected RNA counts as a percentage.',
      'Raw RNA-seq counts, selected rows and the capture’s per-cell QC table.',
      'Check that QC cell IDs exactly match the count columns. In gene_ids mode, sum the counts for these genes in each cell. Divide by its total RNA count, then multiply by 100. Zero total counts give NA.',
      column+' in percent, or NA when the gene set is unavailable.', loader,
      [['Numerator','Sum of raw counts over '+label+' genes in this nucleus.'],['Denominator','Sum of all raw RNA counts in this nucleus.']]),
    step('record', 'Record metric availability', 'Keep the definition together with its values.',
      'Computed or unavailable fraction for all barcodes.',
      'Write the updated capture table, selected gene IDs, reference contract and definition mode. The filter uses its own eligibility rules.',
      'The QC table carries '+column+' and '+status+'_qc_status for later inspection.', loader,
      [['Filtering at this step','None. A missing measurement stays NA.']]),
  ];
}

function atacTransformSteps(file) {
  return [
    step('tfidf', 'Weight the ATAC-seq counts', 'Normalize each peak count for cell depth and peak abundance.',
      'Raw shared-peak counts in the aligned ATAC assay. Each column is one retained nucleus.',
      'For a peak with positive total count, divide its count in a cell by the cell’s total peak counts (TF). Weight by the number of cells divided by the summed count for that peak (IDF). Signac method 1 stores log1p(scale.factor × TF × IDF).',
      'TF-IDF values in the ATAC data layer. Raw peak counts stay in the counts layer.', file,
      [['tfidf_args.method','1'],['tfidf_args.scale.factor','10,000'],['Units','Raw counts are the supplied peak matrix values. Fragment-level QC uses a separate route.']]),
    step('top-peaks', 'Select supported peaks', 'Choose which peak rows enter the LSI fit.',
      'Raw count total for each peak across the selected cells.',
      'FindTopFeatures ranks peak totals using their empirical cumulative distribution. With q5 it retains peaks whose count percentile is strictly greater than 0.05. The percentage refers to the distribution across peaks.',
      'An ordered set of variable ATAC features for dimensional reduction.', file,
      [['min.cutoff','q5 in the preset'],['Ties','Equal count totals share a percentile, so the retained fraction need not be exactly 95%.']]),
    step('svd', 'Fit the accessibility dimensions', 'Compress weighted peak profiles into LSI coordinates.',
      'TF-IDF values for the selected peaks.',
      'Run singular value decomposition (Signac RunSVD) and scale the cell embeddings. Each nucleus obtains a coordinate on each fitted latent semantic indexing (LSI) component.',
      'Cell-by-component coordinates in the lsi reduction.', file,
      [['n','Preset requests 50 components. The counted-peak synthetic example requests 8.'],['scale.embeddings','true'],['tol','0.00001']]),
  ];
}

